// Public endpoint/negative authentication checks only. No Team or user data is created.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
if (process.env.NODE_TLS_REJECT_UNAUTHORIZED === '0') throw Error('TLS verification must remain enabled');
const origin = 'https://teams.hosted.memtrace.io';
const checks = [];
const request = (path, options = {}) => fetch(origin + path, { ...options, redirect: 'error', signal: AbortSignal.timeout(15_000) });
const response = await request('/v1/service');
assert.equal(response.status, 200);
const service = await response.json();
for (const [key, value] of Object.entries({ version: 1, selfServiceTeams: true, accountTeamLimit: 3, workflowRoles: 1, workerActivity: 1 })) {
  assert.equal(service[key], value, `Unexpected Team service capability: ${key}`);
}
assert.match(response.headers.get('strict-transport-security') ?? '', /max-age=31536000/);
checks.push('Public service contract over normally verified HTTPS; HSTS, no Team or operator data exposed');
const redirect = await fetch('http://teams.hosted.memtrace.io/v1/service', { redirect: 'manual', signal: AbortSignal.timeout(15_000) });
assert([301, 302, 307, 308].includes(redirect.status));
assert.equal(redirect.headers.get('location'), origin + '/v1/service');
checks.push('HTTP redirects to the exact HTTPS origin');
const browser = await request('/v1/service', { headers: { origin: 'https://unrelated.example.invalid' } });
assert.equal(browser.status, 403);
assert.equal(browser.headers.get('access-control-allow-origin'), null);
checks.push('Browser-origin requests rejected; no permissive CORS');
const missing = await request('/v1/teams?teamId=' + randomUUID());
assert.equal(missing.status, 401);
checks.push('Team read without a membership capability rejected');
const challenge = await (await request('/v1/team-auth/challenge')).json();
assert.equal(challenge.audience, origin);
assert.match(challenge.nonce, /^[A-Za-z0-9_-]{32,200}$/);
assert(Date.parse(challenge.expiresAt) > Date.now());
assert(Date.parse(challenge.expiresAt) <= Date.now() + 305_000);
const forged = await request('/v1/teams', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Rejected synthetic identity probe', deviceId: randomUUID(), deviceName: 'Synthetic unauthenticated probe', opId: randomUUID(), nonce: challenge.nonce, proof: 'unsigned.synthetic.identity' }) });
assert.equal(forged.status, 403);
checks.push('Nonce binds the exact service origin; unsigned synthetic Team creation rejected');
const keys = await fetch('https://www.memtrace.io/api/memcode/jwks', { redirect: 'error', signal: AbortSignal.timeout(15_000) });
assert.equal(keys.status, 200);
const jwks = await keys.json();
assert(Array.isArray(jwks.keys) && jwks.keys.length > 0 && jwks.keys.length <= 10);
assert(jwks.keys.every(key => key.kty === 'OKP' && key.crv === 'Ed25519' && typeof key.kid === 'string' && !key.d));
checks.push('Official pinned Memtrace public Ed25519 JWKS available; no private signing key exposed');
const result = { origin, at: new Date().toISOString(), checks, note: 'Negative authentication and public transport only. Real browser-account creation/claims, backup restore and reboot must be verified separately before publishing discovery.' };
await writeFile(resolve(import.meta.dirname, '../../tmp/relay-deploy/public-checks.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result, null, 2));
